/* Bare metal boot sector source. The linker assembles it in front of the program to make a bootable image. */
#include "cly.h"

/* Builds the bare metal boot sector source: BIOS disk reads, A20, switch to protected or long mode, page tables for 64-bit, then a jump to the program. */
int rt_boot(Str *s, u32 entry, int nsect, u32 bss, u32 bsslen, int bits)
{
    sadd(s,
        "org 0x7C00\n"
        "bits 16\n"
        "cli\n"
        "xor ax, ax\n"
        "mov ds, ax\n"
        "mov es, ax\n"
        "mov ss, ax\n"
        "mov sp, 0x7C00\n"
        "sti\n"
        "mov [drive], dl\n"
        "mov ah, 8\n"
        "int 0x13\n"
        "jc geo_bad\n"
        "and cl, 0x3F\n"
        "mov [spt], cl\n"
        "inc dh\n"
        "mov [heads], dh\n"
        "jmp geo_ok\n"
        "geo_bad:\n"
        "mov byte [spt], 18\n"
        "mov byte [heads], 2\n"
        "geo_ok:\n"
        "xor ax, ax\n"
        "mov es, ax\n"
        "rd_next:\n"
        "mov dl, [drive]\n"
        "mov si, dap\n"
        "mov ah, 0x42\n"
        "int 0x13\n"
        "jnc rd_ok\n"
        "mov ax, [dap_lba]\n"
        "xor dx, dx\n"
        "movzx cx, byte [spt]\n"
        "div cx\n"
        "inc dx\n"
        "mov cl, dl\n"
        "xor dx, dx\n"
        "movzx bx, byte [heads]\n"
        "div bx\n"
        "mov ch, al\n"
        "shl ah, 6\n"
        "or cl, ah\n"
        "mov dh, dl\n"
        "mov dl, [drive]\n"
        "mov ax, [dap_seg]\n"
        "mov es, ax\n"
        "xor bx, bx\n"
        "mov ax, 0x0201\n"
        "int 0x13\n"
        "jc rd_fail\n"
        "rd_ok:\n"
        "add word [dap_seg], 0x20\n"
        "inc word [dap_lba]\n"
        "dec word [count]\n"
        "jnz rd_next\n"
        "mov ax, 0x2401\n"
        "int 0x15\n"
        "in al, 0x92\n"
        "or al, 2\n"
        "and al, 0xFE\n"
        "out 0x92, al\n"
        "mov ax, 3\n"
        "int 0x10\n"
        "cli\n"
        "lgdt [gdtr]\n"
        "mov eax, cr0\n"
        "or al, 1\n"
        "mov cr0, eax\n"
        "jmp 0x08:pm\n"
        "rd_fail:\n"
        "mov si, errmsg\n"
        "er_l:\n"
        "lodsb\n"
        "test al, al\n"
        "jz er_h\n"
        "mov ah, 0x0E\n"
        "int 0x10\n"
        "jmp er_l\n"
        "er_h:\n"
        "hlt\n"
        "jmp er_h\n"
        "bits 32\n"
        "pm:\n"
        "mov ax, 0x10\n"
        "mov ds, ax\n"
        "mov es, ax\n"
        "mov fs, ax\n"
        "mov gs, ax\n"
        "mov ss, ax\n"
        "mov esp, 0x7C00\n");
    if (bits == 64) {
        sadd(s,
            "mov edi, 0x1000\n"
            "xor eax, eax\n"
            "mov ecx, 0xC00\n"
            "cld\n"
            "rep stosd\n"
            "mov dword [0x1000], 0x2003\n"
            "mov dword [0x2000], 0x3003\n"
            "mov edi, 0x3000\n"
            "mov eax, 0x83\n"
            "mov ecx, 512\n"
            "pt_l:\n"
            "mov [edi], eax\n"
            "add eax, 0x200000\n"
            "add edi, 8\n"
            "loop pt_l\n"
            "mov eax, 0x1000\n"
            "mov cr3, eax\n"
            "mov eax, cr4\n"
            "or al, 0x20\n"
            "mov cr4, eax\n"
            "mov ecx, 0xC0000080\n"
            "rdmsr\n"
            "or ah, 1\n"
            "wrmsr\n"
            "mov eax, cr0\n"
            "or eax, 0x80000000\n"
            "mov cr0, eax\n"
            "jmp 0x18:lm\n"
            "bits 64\n"
            "lm:\n");
        sfmt(s, "mov edi, %u\nmov ecx, %u\nxor eax, eax\nrep stosb\nmov eax, %u\njmp rax\n", bss, bsslen, entry);
    } else {
        sfmt(s, "mov edi, %u\nmov ecx, %u\nxor eax, eax\ncld\nrep stosb\nmov eax, %u\njmp eax\n", bss, bsslen, entry);
    }
    sadd(s,
        "gdt:\n"
        "dq 0\n"
        "dq 0x00CF9A000000FFFF\n"
        "dq 0x00CF92000000FFFF\n"
        "dq 0x00AF9A000000FFFF\n"
        "gdtr:\n"
        "dw 31\n"
        "dd gdt\n"
        "drive: db 0\n"
        "spt: db 0\n"
        "heads: db 0\n"
        "errmsg: db 'Disk read error', 0\n");
    sfmt(s, "count: dw %d\n", nsect);
    sadd(s,
        "dap: db 16, 0\n"
        "dw 1\n"
        "dw 0\n"
        "dap_seg: dw 0x0800\n"
        "dap_lba: dd 1, 0\n"
        "times 510-($-$$) db 0\n"
        "dw 0xAA55\n");
    return 1;
}

